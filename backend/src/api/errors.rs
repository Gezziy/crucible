//! Standardized error response structures and response helpers for the Crucible API.

use axum::{
    http::{header, StatusCode},
    response::{IntoResponse, Response},
    Json,
};
use serde::{Deserialize, Serialize};

/// Standardized JSON error response returned by middlewares and fallbacks.
#[derive(Debug, Serialize, Deserialize)]
pub struct ErrorResponse {
    pub code: String,
    pub message: String,
    pub timestamp: String,
}

/// RFC 7807 compliant Problem Details representation.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ProblemDetails {
    /// URI reference identifying the problem type.
    #[serde(rename = "type")]
    pub type_: String,
    /// Short, human-readable summary of the problem type.
    pub title: String,
    /// HTTP status code generated by the origin server.
    pub status: u16,
    /// Human-readable explanation specific to this occurrence of the problem.
    pub detail: String,
    /// Machine-readable application error code.
    pub code: String,
    /// Human-readable error message (compatibility alias for detail).
    pub message: String,
    /// Timestamp of when the error occurred.
    pub timestamp: String,
}

/// Create an RFC 7807 compliant Problem Details response with `application/problem+json`.
pub fn make_problem_response(status: StatusCode, code: &str, detail: &str) -> Response {
    let title = status.canonical_reason().unwrap_or("Error").to_string();
    let problem = ProblemDetails {
        type_: "about:blank".to_string(),
        title,
        status: status.as_u16(),
        detail: detail.to_string(),
        code: code.to_string(),
        message: detail.to_string(),
        timestamp: chrono::Utc::now().to_rfc3339(),
    };
    (
        status,
        [(header::CONTENT_TYPE, "application/problem+json")],
        Json(problem),
    )
        .into_response()
}

/// Create a standardized axum JSON response with a timestamp.
pub fn make_error_response(status: StatusCode, code: &str, message: &str) -> Response {
    (
        status,
        Json(ErrorResponse {
            code: code.to_string(),
            message: message.to_string(),
            timestamp: chrono::Utc::now().to_rfc3339(),
        }),
    )
        .into_response()
}

/// A fallback handler returning a standardized 404 JSON response.
pub async fn api_fallback() -> impl IntoResponse {
    make_error_response(
        StatusCode::NOT_FOUND,
        "not_found",
        "The requested resource was not found",
    )
}
